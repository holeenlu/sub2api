<script setup lang="ts">
import { computed, toRef } from 'vue';
import { useI18n } from 'vue-i18n';
import type { AdminGroup, GroupPlatform } from '@/features/access-policy/api/groupTypes';
import Select from '@/shared/ui/Select.vue';
import Toggle from '@/shared/ui/Toggle.vue';
import Icon from '@/shared/ui/icons/Icon.vue';
import { useGroupPresentation } from '@/features/access-policy/presentation/context'
const { platformLabel: platformLabel } = useGroupPresentation();
import { useDraftSection } from '@/shared/lib/useDraftSection';
import type { GroupAccessDraft } from '../model/groupAccessDraft';
const props = defineProps<{ modelValue: Readonly<GroupAccessDraft>; groups: AdminGroup[]; groupId: number; editable: (field: string) => boolean }>()
const emit = defineEmits<{ patch: [draft: Partial<GroupAccessDraft>] }>()
const editForm = useDraftSection(() => props.modelValue, patch => emit('patch', patch))
const groups = toRef(props, 'groups')
const editingGroup = computed(() => ({ id: props.groupId }))
const { t } = useI18n()
const canEditGroupField = (field: string, _creating: boolean) => props.editable(field)
const editStatusOptions = computed(() => [
  { value: "active", label: t("admin.accounts.status.active") },
  { value: "inactive", label: t("admin.accounts.status.inactive") },
]);
const fallbackGroupOptionsForEdit = computed(() => {
  const options: { value: number | null; label: string }[] = [
    { value: null, label: t("admin.groups.claudeCode.noFallback") },
  ];
  const currentId = editingGroup.value?.id;
  const eligibleGroups = groups.value.filter(
    (g) =>
      g.platform === "anthropic" &&
      !g.claude_code_only &&
      g.status === "active" &&
      g.id !== currentId,
  );
  eligibleGroups.forEach((g) => {
    options.push({ value: g.id, label: g.name });
  });
  return options;
});
const invalidRequestFallbackOptionsForEdit = computed(() => {
  const options: { value: number | null; label: string }[] = [
    { value: null, label: t("admin.groups.invalidRequestFallback.noFallback") },
  ];
  const currentId = editingGroup.value?.id;
  const eligibleGroups = groups.value.filter(
    (g) =>
      g.platform === "anthropic" &&
      g.status === "active" &&
      g.subscription_type !== "subscription" &&
      g.fallback_group_id_on_invalid_request === null &&
      g.id !== currentId,
  );
  eligibleGroups.forEach((g) => {
    options.push({ value: g.id, label: g.name });
  });
  return options;
});
const canCopyAccountsFromGroup = (targetPlatform: GroupPlatform, sourcePlatform: GroupPlatform) =>
  targetPlatform === "composite" || sourcePlatform === targetPlatform;
const copyAccountsGroupLabel = (g: AdminGroup) => {
  const count = g.account_count || 0;
  const platform = t("admin.groups.platforms." + g.platform, platformLabel(g.platform));
  return `${g.name} - ${platform} (${t("admin.groups.accountsCount", { count })})`;
};
const copyAccountsGroupOptionsForEdit = computed(() => {
  const currentId = editingGroup.value?.id;
  const eligibleGroups = groups.value.filter(
    (g) =>
      canCopyAccountsFromGroup(editForm.platform, g.platform) &&
      (g.account_count || 0) > 0 &&
      g.id !== currentId,
  );
  return eligibleGroups.map((g) => ({
    value: g.id,
    label: copyAccountsGroupLabel(g),
  }));
});
const toggleEditScope = (scope: string) => {
  const idx = editForm.supported_model_scopes.indexOf(scope);
  if (idx === -1) {
    editForm.supported_model_scopes.push(scope);
  } else {
    editForm.supported_model_scopes.splice(idx, 1);
  }
};
</script>
