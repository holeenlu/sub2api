<script setup lang="ts">
import { computed, ref, toRefs, onMounted, onScopeDispose, watch, type ComponentPublicInstance } from 'vue'
import { useI18n } from 'vue-i18n'
import DataTable from '@/shared/ui/DataTable.vue'
import EmptyState from '@/shared/ui/EmptyState.vue'
import Icon from '@/shared/ui/icons/Icon.vue'
import type { Column } from '@/shared/ui/tableTypes'
import { formatDateTime } from '@/shared/lib/format'
import { formatKeyCost, isKnownKeyMetric } from '../model/keyUsageDisplay'
import { maskApiKey } from '@/shared/lib/maskApiKey'
import type { ApiKey } from '../api/types'
import type { KeyGroupOption } from '../queries/useKeyGroups'
import { useKeysServices, type KeyUsageSummary } from '../services'
const props = defineProps<{
  columns: Column[]; apiKeys: ApiKey[]; loading: boolean; selectedIds: number[];
  usageStats: Record<string, KeyUsageSummary>; userGroupRates: Record<number, number>; groupOptions: KeyGroupOption[]
}>()
const emit = defineEmits<{
  selection: [ids: Array<string | number>]; sort: [key: string, order: 'asc' | 'desc']; create: [];
  edit: [key: ApiKey]; remove: [key: ApiKey]; toggle: [key: ApiKey]; use: [key: ApiKey]; resetRate: [key: ApiKey];
  group: [key: ApiKey, id: number]; refreshGroups: []
}>()
const { apiKeys, groupOptions } = toRefs(props)
const { t } = useI18n()
const services = useKeysServices()
const { GroupBadge, GroupOptionItem } = services.components
const handleSelectionChange = (ids: Array<string | number>) => emit('selection', ids)
const handleSort = (key: string, order: 'asc' | 'desc') => emit('sort', key, order)
const editKey = (key: ApiKey) => emit('edit', key)
const confirmDelete = (key: ApiKey) => emit('remove', key)
const toggleKeyStatus = (key: ApiKey) => emit('toggle', key)
const openUseKeyModal = (key: ApiKey) => emit('use', key)
const confirmResetRateLimitFromTable = (key: ApiKey) => emit('resetRate', key)
const copiedKeyId = ref<number | null>(null)
let copiedTimer: ReturnType<typeof setTimeout> | undefined
let alive = true
async function copyToClipboard(text: string, keyId: number): Promise<void> {
  const scope = services.scopeKey.value
  const success = await services.copyText(text, t('keys.copied'))
  if (!success || !alive || scope !== services.scopeKey.value) return
  copiedKeyId.value = keyId
  clearTimeout(copiedTimer)
  copiedTimer = setTimeout(() => { copiedKeyId.value = null }, 800)
}
const groupSelectorKeyId = ref<number | null>(null)
const dropdownRef = ref<HTMLElement | null>(null)
const dropdownPosition = ref<{ top?: number; bottom?: number; left: number } | null>(null)
const groupButtonRefs = ref(new Map<number, HTMLElement>())
const selectedKeyForGroup = computed(() => apiKeys.value.find(key => key.id === groupSelectorKeyId.value) ?? null)
function setGroupButtonRef(id: number, el: Element | ComponentPublicInstance | null): void {
  if (el instanceof HTMLElement) groupButtonRefs.value.set(id, el)
  else groupButtonRefs.value.delete(id)
}
const groupSearchQuery = ref('')
const filteredGroupOptions = computed(() => {
  const search = groupSearchQuery.value.trim().toLowerCase()
  return groupOptions.value.filter(option => !search || option.label.toLowerCase().includes(search) || option.description?.toLowerCase().includes(search))
})
function changeGroup(id: number): void {
  const key = selectedKeyForGroup.value
  groupSelectorKeyId.value = null; dropdownPosition.value = null
  if (key && key.group_id !== id) emit('group', key, id)
}
function closeGroupSelector(event: MouseEvent): void {
  const target = event.target
  if (!(target instanceof Element) || (!target.closest('[data-key-group-trigger]') && !dropdownRef.value?.contains(target))) {
    groupSelectorKeyId.value = null; dropdownPosition.value = null
  }
}
const now = ref(new Date())
let timer: ReturnType<typeof setInterval> | undefined
const openGroupSelector = (key: ApiKey) => {
  if (groupSelectorKeyId.value === key.id) {
    groupSelectorKeyId.value = null
    dropdownPosition.value = null
  } else {
    emit('refreshGroups')
    const buttonEl = groupButtonRefs.value.get(key.id)
    if (buttonEl) {
      const rect = buttonEl.getBoundingClientRect()
      const dropdownEstHeight = 400 // estimated max dropdown height
      const dropdownEstWidth = Math.min(380, window.innerWidth - 16)
      const spaceBelow = window.innerHeight - rect.bottom
      const spaceAbove = rect.top
      // 夹取 left，避免窄屏下浮层超出视口右缘
      const left = Math.max(8, Math.min(rect.left, window.innerWidth - dropdownEstWidth - 8))

      if (spaceBelow < dropdownEstHeight && spaceAbove > spaceBelow) {
        // Not enough space below, pop upward
        dropdownPosition.value = {
          bottom: window.innerHeight - rect.top + 4,
          left
        }
      } else {
        // Default: pop downward
        dropdownPosition.value = {
          top: rect.bottom + 4,
          left
        }
      }
    }
    groupSelectorKeyId.value = key.id
    groupSearchQuery.value = ''
  }
}

function formatResetTime(resetAt: string | null): string {
  if (!resetAt) return ''
  const diff = new Date(resetAt).getTime() - now.value.getTime()
  if (diff <= 0) return t('keys.resetNow')
  const days = Math.floor(diff / 86400000)
  const hours = Math.floor((diff % 86400000) / 3600000)
  const mins = Math.floor((diff % 3600000) / 60000)
  if (days > 0) return `${days}d ${hours}h`
  if (hours > 0) return `${hours}h ${mins}m`
  return `${mins}m`
}


watch(services.scopeKey, () => { groupSelectorKeyId.value = null; copiedKeyId.value = null; clearTimeout(copiedTimer) }, { flush: 'sync' })
onMounted(() => { document.addEventListener('click', closeGroupSelector); timer = setInterval(() => { now.value = new Date() }, 60000) })
onScopeDispose(() => { alive = false; clearInterval(timer); clearTimeout(copiedTimer); document.removeEventListener('click', closeGroupSelector) })
</script>
