package routes

import (
	"github.com/Wei-Shaw/sub2api/internal/handler"
	"github.com/Wei-Shaw/sub2api/internal/server/middleware"
	"github.com/gin-gonic/gin"
)

func RegisterVendorRoutes(v1 *gin.RouterGroup, h *handler.Handlers, jwt middleware.JWTAuthMiddleware, limiter *middleware.PanelRateLimiter) {
	if h.Vendor == nil {
		return
	}
	v := v1.Group("/vendor", gin.HandlerFunc(jwt), limiter.Global(), h.Vendor.Scope)
	v.GET("/me", h.Vendor.Me)
	children := v.Group("/vendors")
	children.GET("", h.Vendor.List)
	children.POST("", h.Vendor.Create)
	children.GET("/:id", h.Vendor.Get)
	children.PATCH("/:id", h.Vendor.Update)
	a := v.Group("/accounts")
	a.GET("", h.VendorAccount.List)
	a.POST("", h.VendorAccount.Create)
	a.POST("/import/preview", h.VendorAccount.ImportPreview)
	a.POST("/import", h.VendorAccount.Import)
	a.POST("/export", h.Vendor.ExportStepUp, h.VendorAccount.Export)
	a.GET("/:id", h.VendorAccount.Get)
	a.PATCH("/:id", h.VendorAccount.Update)
	a.DELETE("/:id", h.VendorAccount.Delete)
	a.DELETE("/:id/authorizations/:mode", h.VendorAccount.RevokeAuthorization)
	a.POST("/:id/pause", h.VendorAccount.Pause)
	a.POST("/:id/resume", h.VendorAccount.Resume)
	a.POST("/:id/refresh", h.VendorAccount.Refresh)
	a.POST("/:id/usage-refresh", h.VendorAccount.UsageRefresh)
	a.POST("/:id/probe", h.VendorAccount.Probe)
	a.POST("/:id/sync", h.VendorAccount.Sync)
	a.GET("/:id/usage", h.VendorUsage.AccountUsage)
	registerVendorOAuth(v, h)
	p := v.Group("/proxies")
	p.GET("", h.VendorProxy.List)
	p.POST("", h.VendorProxy.Create)
	p.POST("/import/preview", h.VendorProxy.ImportPreview)
	p.POST("/import", h.VendorProxy.Import)
	p.POST("/export", h.VendorProxy.Export)
	p.POST("/batch-delete", h.VendorProxy.BatchDelete)
	p.GET("/:id", h.VendorProxy.Get)
	p.PATCH("/:id", h.VendorProxy.Update)
	p.DELETE("/:id", h.VendorProxy.Delete)
	p.POST("/:id/test", h.VendorProxy.Test)
	p.POST("/:id/quality-check", h.VendorProxy.QualityCheck)
	v.GET("/usage/summary", h.VendorUsage.Summary)
	v.GET("/usage/trend", h.VendorUsage.Trend)
	v.GET("/usage/accounts", h.VendorUsage.Accounts)
	v.GET("/audit-logs", h.Vendor.Audit)
	v.GET("/payables", h.VendorSettlement.PayableList)
	v.GET("/payables/:id", h.VendorSettlement.PayableGet)
	v.GET("/payables/:id/export", h.VendorSettlement.PayableExport)
	v.GET("/settlements", h.VendorSettlement.List)
	v.POST("/payables/preview", h.VendorSettlement.Preview)
	v.POST("/payables", h.VendorSettlement.Create)
	v.POST("/payables/:id/confirm", h.VendorSettlement.Confirm)
	v.POST("/payables/:id/void", h.VendorSettlement.Void)
	v.POST("/payables/:id/payments", h.VendorSettlement.Payment)
	v.POST("/payables/:id/payments/:payment_id/reverse", h.VendorSettlement.Reverse)
	v.POST("/payables/:id/adjustments", h.VendorSettlement.Adjustment)
	v.GET("/settlements/:id", h.VendorSettlement.Get)
	v.GET("/settlements/:id/export", h.VendorSettlement.Export)
}
func registerVendorOAuth(v *gin.RouterGroup, h *handler.Handlers) {
	v.POST("/oauth/:platform/sessions", h.VendorAccount.StartOAuth)
	v.POST("/oauth/:platform/sessions/:session_id/complete", h.VendorAccount.CompleteOAuth)
	v.PATCH("/oauth/:platform/sessions/:session_id/proxy", h.VendorAccount.RebindOAuthProxy)
}
func registerVendorAdminRoutes(admin *gin.RouterGroup, h *handler.Handlers) {
	if h.Vendor == nil {
		return
	}
	v := admin.Group("/vendors", h.Vendor.SuperOnly)
	v.GET("", h.Vendor.List)
	v.POST("", h.Vendor.Create)
	v.GET("/group-supply", h.Vendor.GroupSupply)
	v.GET("/audit-logs", h.Vendor.Audit)
	v.GET("/usage", h.VendorUsage.AdminUsage)
	v.POST("/identity-reconciliation", h.VendorAccount.ReconcileIdentity)
	v.GET("/usage/export", h.VendorUsage.AdminExport)
	v.GET("/settlements", h.VendorSettlement.AdminList)
	v.POST("/settlements/preview", h.VendorSettlement.Preview)
	v.POST("/settlements", h.VendorSettlement.Create)
	v.GET("/settlements/:id", h.VendorSettlement.AdminGet)
	v.POST("/settlements/:id/confirm", h.VendorSettlement.Confirm)
	v.POST("/settlements/:id/void", h.VendorSettlement.Void)
	v.POST("/settlements/:id/payments", h.VendorSettlement.Payment)
	v.POST("/settlements/:id/payments/:payment_id/reverse", h.VendorSettlement.Reverse)
	v.POST("/settlements/:id/adjustments", h.VendorSettlement.Adjustment)
	v.GET("/settlements/:id/export", h.VendorSettlement.AdminExport)
	v.GET("/:id", h.Vendor.Get)
	v.PATCH("/:id", h.Vendor.Update)
	registerVendorOAuth(v.Group("", h.Vendor.AdminScope), h)
	// Supplier-specific actions absent from the native admin routes reuse the same handlers.
	a := admin.Group("/accounts", h.Vendor.SuperOnly, h.Vendor.AdminScope)
	a.POST("/import/preview", h.VendorAccount.ImportPreview)
	a.POST("/import", h.VendorAccount.Import)
	a.POST("/export", h.Vendor.ExportStepUp, h.VendorAccount.Export)
	a.DELETE("/:id/authorizations/:mode", h.VendorAccount.RevokeAuthorization)
	a.POST("/:id/pause", h.VendorAccount.Pause)
	a.POST("/:id/resume", h.VendorAccount.Resume)
	a.POST("/:id/usage-refresh", h.VendorAccount.UsageRefresh)
	a.POST("/:id/probe", h.VendorAccount.Probe)
	a.POST("/:id/sync", h.VendorAccount.Sync)
	p := admin.Group("/proxies", h.Vendor.SuperOnly, h.Vendor.AdminScope)
	p.POST("/import/preview", h.VendorProxy.ImportPreview)
	p.POST("/import", h.VendorProxy.Import)
	admin.POST("/proxies/export", h.Vendor.SuperOnly, h.Vendor.AdminReadScope, h.VendorProxy.Export)
}
